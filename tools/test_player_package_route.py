def align_executable(executable: bytes) -> bytes:
    """Make a source-owned ELF satisfy the ISO preflight's alignment congruence.

    The generated guests use load-relative zero addresses. Only the program
    headers' congruence field is written; no code or data byte changes.
    """
    patched = bytearray(executable)
    phoff = struct.unpack_from("<I", patched, 28)[0]
    phnum = struct.unpack_from("<H", patched, 44)[0]
    for index in range(phnum):
        struct.pack_into("<I", patched, phoff + index * 32 + 28, 0x100)
    return bytes(patched)


def fixed_address_exec_elf(executable: bytes, base: int) -> bytes:
    """Turn the source-owned PRX fixture into a relocated, fixed-address ET_EXEC."""
    loaded = prxload.Prx(executable, base)
    loaded.relocate()
    fixed = bytearray(executable)
    phoff = struct.unpack_from("<I", fixed, 28)[0]
    phentsize = struct.unpack_from("<H", fixed, 42)[0]
    phnum = struct.unpack_from("<H", fixed, 44)[0]
    shoff = struct.unpack_from("<I", fixed, 32)[0]
    shentsize = struct.unpack_from("<H", fixed, 46)[0]
    shnum = struct.unpack_from("<H", fixed, 48)[0]
    entry = struct.unpack_from("<I", fixed, 24)[0]
    struct.pack_into("<H", fixed, 16, 2)  # ET_EXEC
    struct.pack_into("<I", fixed, 24, base + entry)
    loads = []
    for index in range(phnum):
        offset = phoff + index * phentsize
        p_type, p_offset, vaddr, paddr, filesz, memsz = struct.unpack_from(
            "<6I", fixed, offset
        )
        if p_type != 1:
            continue
        loads.append((vaddr, vaddr + memsz))
        relocated_start = base + vaddr - loaded.lo
        fixed[p_offset:p_offset + filesz] = loaded.mem[
            relocated_start:relocated_start + filesz
        ]
        struct.pack_into("<II", fixed, offset + 8, base + vaddr, base + paddr)
    for index in range(1, shnum):
        offset = shoff + index * shentsize
        section_type, flags, address = struct.unpack_from("<III", fixed, offset + 4)
        if section_type in {4, 9, 0x700000A0, 0x700000A1}:
            struct.pack_into("<I", fixed, offset + 4, 0)
            continue
        if flags & 2 and any(start <= address <= end for start, end in loads):
            struct.pack_into("<I", fixed, offset + 12, base + address)
    return bytes(fixed)


