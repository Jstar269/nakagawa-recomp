"""Embed the vendored nk_ui assets in ``src/ui/nk_ui_assets.c``.

The native player draws the launcher's button prompts from Kenney's CC0 "Input
Prompts" glyphs and can play three CC0 "Interface Sounds" clips. Both packs are
vendored, file by file, under ``third_party/kenney/`` (see its ``PROVENANCE.md``).
Embedding their bytes in the binary means the player needs no extra staged
files and no run-time path lookup, and the SDL-free tests decode exactly the
bytes the player ships.

Every ``*.png`` under ``third_party/kenney/input-prompts/`` and every ``*.wav``
under ``third_party/kenney/interface-sounds/`` is embedded, sorted by name, as
``"<pack>/<file>"``. The output is deterministic: the same inputs give the same
bytes on every host.

    python tools/gen_ui_assets.py                  # rewrite src/ui/nk_ui_assets.c
    python tools/gen_ui_assets.py --out <file>     # write elsewhere
    python tools/gen_ui_assets.py --check          # exit 1 when the committed file is stale

``python tools/regen_all.py`` runs this step with the other generators.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path("src/ui/nk_ui_assets.c")
PACKS: tuple[tuple[str, str], ...] = (
    ("input-prompts", "*.png"),
    ("interface-sounds", "*.wav"),
)
# Refuse anything that is plainly not a small UI asset.
MAX_ASSET_BYTES = 64 * 1024
BYTES_PER_LINE = 16


def collect(root: Path = ROOT) -> list[tuple[str, bytes]]:
    assets: list[tuple[str, bytes]] = []
    for pack, pattern in PACKS:
        directory = root / "third_party" / "kenney" / pack
        files = sorted(directory.glob(pattern), key=lambda path: path.name)
        if not files:
            raise SystemExit(f"gen_ui_assets: no {pattern} under {directory}")
        for path in files:
            data = path.read_bytes()
            if not data or len(data) > MAX_ASSET_BYTES:
                raise SystemExit(f"gen_ui_assets: {path.name} is {len(data)} bytes")
            assets.append((f"{pack}/{path.name}", data))
    return assets


def _symbol(name: str) -> str:
    return "k_" + "".join(ch if ch.isalnum() else "_" for ch in name)


def render(assets: list[tuple[str, bytes]]) -> str:
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Copyright (C) 2026 the Nakagawa Recomp authors */",
        "/* AUTOGENERATED FILE - DO NOT EDIT DIRECTLY */",
        "/* Generated by tools/gen_ui_assets.py from third_party/kenney/ (CC0-1.0 assets by Kenney,",
        "   www.kenney.nl; see third_party/kenney/PROVENANCE.md). */",
        "",
        '#include "nk_ui_assets.h"',
        "",
        "#include <string.h>",
        "",
    ]
    total = 0
    for name, data in assets:
        total += len(data)
        lines.append(f"/* {name}, {len(data)} bytes */")
        lines.append(f"static const unsigned char {_symbol(name)}[{len(data)}] = {{")
        for start in range(0, len(data), BYTES_PER_LINE):
            chunk = data[start:start + BYTES_PER_LINE]
            lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append(f"/* {len(assets)} assets, {total} bytes. */")
    lines.append("const NkUiEmbeddedAsset nk_ui_embedded_assets[] = {")
    for name, data in assets:
        lines.append(f'    {{"{name}", {_symbol(name)}, {len(data)}u}},')
    lines.append("};")
    lines.append("")
    lines.append(
        "const size_t nk_ui_embedded_asset_count = "
        "sizeof(nk_ui_embedded_assets) / sizeof(nk_ui_embedded_assets[0]);"
    )
    lines.append("")
    lines.append("const NkUiEmbeddedAsset *nk_ui_embedded_asset(const char *name) {")
    lines.append("    size_t i;")
    lines.append("    if (name == NULL) {")
    lines.append("        return NULL;")
    lines.append("    }")
    lines.append("    for (i = 0; i < nk_ui_embedded_asset_count; ++i) {")
    lines.append("        if (strcmp(nk_ui_embedded_assets[i].name, name) == 0) {")
    lines.append("            return &nk_ui_embedded_assets[i];")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=ROOT / OUTPUT, help="output file")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when the committed file differs from a fresh generation")
    args = parser.parse_args(argv)
    text = render(collect())
    if args.check:
        current = (ROOT / OUTPUT).read_bytes() if (ROOT / OUTPUT).is_file() else b""
        if current != text.encode("utf-8"):
            print(f"gen_ui_assets: {OUTPUT.as_posix()} is stale; run python tools/regen_all.py",
                  file=sys.stderr)
            return 1
        print(f"gen_ui_assets: {OUTPUT.as_posix()} is current")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(text.encode("utf-8"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
