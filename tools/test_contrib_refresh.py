"""``tools/contrib_refresh.py`` reproduces the maintainer's controls for the ordinary case.

The positive test builds a real Git repository and compares the contributor tool's
two outputs, byte for byte, against ``provenance_refresh.generate_controls`` -- the
function the maintainer's ``provenance_refresh.py`` calls -- run over the same
candidate tree and a matching trusted-ledger fixture.  The refusal tests assert
that every case the public controls cannot describe fails closed instead of being
refreshed.

All fixtures are synthetic and offline; no test reads the real private ledger or
the real repository's controls.  ``SyntheticControlRepository`` is reused from
``tools/test_provenance_control_merge.py`` for the refusal cases, so the tiny-repo
pattern is one implementation rather than two.
"""

from __future__ import annotations

import hashlib
from contextlib import redirect_stderr, redirect_stdout
from io import StringIO
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))

import contrib_refresh  # noqa: E402
import provenance_refresh  # noqa: E402
import test_provenance_control_merge as merge_fixture  # noqa: E402

POLICY = "assets/public_source_profile.json"
LEDGER = "assets/public_provenance_ledger.json"
EXPORT = "PUBLIC_EXPORT.json"
PATH_A = "docs/alpha.md"
PATH_B = "tools/beta.py"

ALPHA = b"# alpha\n\noriginal\n"
BETA = b'"""beta."""\n\nVALUE = 1\n'
BETA_EDITED = b'"""beta."""\n\nVALUE = 2\n'


def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, check=False)


def _canonical(document: dict) -> bytes:
    return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


class TrustedLedgerRepository:
    """A tiny repository whose committed ledger is the trusted authority's baseline.

    Both committed control files are generated by the real refresh
    (``provenance_refresh.generate_controls``, over the base tree and a synthetic
    trusted ledger), so the contributor tool's copy-and-rehash and the real
    refresh's baseline-and-rehash start from the same bytes.  That is what makes
    the byte-for-byte comparison in ``ContribRefreshEqualsRealRefreshTests`` about
    the code under test rather than about the fixture.
    """

    POLICY_DOCUMENT = {
        "name": "contrib-refresh-synthetic",
        "profile_version": "1.0.0",
        "min_tool_version": "0.4.0",
        "build_mode": "PUBLIC_SAFE=1",
        "default_disposition": "REJECT",
        "exclude_prefixes": [],
        "exclude_globs": [],
        "exclude_paths": [],
        "include_paths": [POLICY, PATH_A, PATH_B],
    }

    def __init__(self, tmp: str) -> None:
        self.tmp = Path(tmp)
        self.root = self.tmp / "repo"
        self.root.mkdir()
        self.work = self.tmp / "work"
        self.work.mkdir()
        self.trusted_ledger = self.tmp / "trusted-ledger.json"
        self.trusted_ledger.write_bytes(_canonical({
            "schema_version": 1,
            "vocabulary": [],
            "records": [
                {
                    "id": "beta-record",
                    "paths": [PATH_B],
                    "classification": "project-authored-independent",
                    "evidence_tier": "S",
                },
                {
                    "id": "alpha-record",
                    "paths": [PATH_A],
                    "classification": "reviewed-documentation",
                    "evidence_tier": "D",
                },
            ],
        }))
        _git(self.root, "init", "-q", "-b", "main")
        _git(self.root, "config", "user.email", "contrib-refresh@example.invalid")
        _git(self.root, "config", "user.name", "contrib refresh")
        _git(self.root, "config", "commit.gpgsign", "false")
        _git(self.root, "config", "core.autocrlf", "false")
        _git(self.root, "config", "core.eol", "lf")
        self._write({POLICY: _canonical(self.POLICY_DOCUMENT), PATH_A: ALPHA, PATH_B: BETA})
        self._commit("seed")
        seed = _git(self.root, "rev-parse", "HEAD").stdout.strip()
        # The committed controls are exactly the authority baseline for this tree,
        # so the two generation routes start identical.
        seed_tree = _git(self.root, "rev-parse", f"{seed}^{{tree}}").stdout.strip()
        controls = provenance_refresh.generate_controls(
            repo=self.root, base_rev=seed, candidate_tree=seed_tree,
            trusted_ledger=self.trusted_ledger, workdir=self.work / "seed-controls",
        )
        self._write({
            LEDGER: controls.generated_ledger_bytes,
            EXPORT: controls.generated_export_bytes,
        })
        self.base = self._commit("base")

    def _write(self, files: dict[str, bytes]) -> None:
        for path, raw in files.items():
            target = self.root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)

    def _commit(self, message: str) -> str:
        _git(self.root, "add", "-A")
        _git(self.root, "commit", "-qm", message)
        return _git(self.root, "rev-parse", "HEAD").stdout.strip()

    def controls(self) -> tuple[bytes, bytes]:
        return (self.root / LEDGER).read_bytes(), (self.root / EXPORT).read_bytes()


class ContribRefreshEqualsRealRefreshTests(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.fixture = TrustedLedgerRepository(self._tmp.name)
        self.root = self.fixture.root

    def test_positive_case_is_byte_identical_to_the_real_refresh(self) -> None:
        """The contributor tool's two files equal the maintainer generator's, byte for byte."""
        self.fixture._write({PATH_B: BETA_EDITED})
        _git(self.root, "add", PATH_B)
        candidate_tree = _git(self.root, "write-tree").stdout.strip()
        reference = provenance_refresh.generate_controls(
            repo=self.root,
            base_rev=self.fixture.base,
            candidate_tree=candidate_tree,
            trusted_ledger=self.fixture.trusted_ledger,
            workdir=self.fixture.work / "reference",
        )
        rc = contrib_refresh.main(["--repo", str(self.root), "--base", self.fixture.base])
        self.assertEqual(rc, 0)
        self.assertEqual((self.root / LEDGER).read_bytes(), reference.generated_ledger_bytes)
        self.assertEqual((self.root / EXPORT).read_bytes(), reference.generated_export_bytes)
        # And the refreshed ledger carries the new content hash for the changed path.
        entries = {e["path"]: e for e in json.loads((self.root / LEDGER).read_bytes())["entries"]}
        self.assertEqual(entries[PATH_B]["sha256"], hashlib.sha256(BETA_EDITED).hexdigest())

    def test_check_writes_nothing_and_names_each_path(self) -> None:
        before = self.fixture.controls()
        self.fixture._write({PATH_A: b"# alpha\n\nedited under --check\n"})
        _git(self.root, "add", PATH_A)
        buffer = StringIO()
        with redirect_stdout(buffer):
            rc = contrib_refresh.main(["--repo", str(self.root), "--base", self.fixture.base, "--check"])
        self.assertEqual(rc, 0)
        self.assertEqual(self.fixture.controls(), before)
        self.assertIn(PATH_A, buffer.getvalue())
        self.assertIn("wrote nothing", buffer.getvalue())


class ContribRefreshRefusalTests(unittest.TestCase):
    """Every case the public controls cannot describe must fail closed."""

    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.repo = merge_fixture.SyntheticControlRepository(Path(self._tmp.name))
        self.root = self.repo.root
        self.base = self.repo.base

    def _run(self) -> tuple[int, str]:
        buffer = StringIO()
        with redirect_stderr(buffer):
            rc = contrib_refresh.main(["--repo", str(self.root), "--base", self.base])
        return rc, buffer.getvalue()

    def test_new_public_path_is_refused(self) -> None:
        (self.root / "tools/new_experiment.py").write_bytes(b"# new file\n")
        _git(self.root, "add", "-A")
        rc, output = self._run()
        self.assertEqual(rc, 1)
        self.assertIn("NEW_PUBLIC_PATH", output)

    def test_removed_public_path_is_refused(self) -> None:
        _git(self.root, "rm", "-q", merge_fixture.PATH_A)
        rc, output = self._run()
        self.assertEqual(rc, 1)
        self.assertIn("REMOVED_PUBLIC_PATH", output)

    def test_policy_change_is_refused(self) -> None:
        document = json.loads((self.root / POLICY).read_bytes())
        document["include_paths"] = [p for p in document["include_paths"] if p != merge_fixture.PATH_A]
        (self.root / POLICY).write_bytes(_canonical(document))
        _git(self.root, "add", POLICY)
        rc, output = self._run()
        self.assertEqual(rc, 1)
        self.assertIn("POLICY_CHANGED", output)

    def test_unresolved_entry_is_refused(self) -> None:
        # tools/beta.py has no trusted record in this fixture, so its committed
        # public entry is `unresolved`.
        (self.root / merge_fixture.PATH_B).write_bytes(b'"""beta."""\n\nVALUE = 3\n')
        _git(self.root, "add", merge_fixture.PATH_B)
        rc, output = self._run()
        self.assertEqual(rc, 1)
        self.assertIn("UNRESOLVED_ENTRY", output)

    def test_an_unstaged_edit_is_refused(self) -> None:
        (self.root / merge_fixture.PATH_A).write_bytes(b"# alpha\n\nnot staged\n")
        rc, output = self._run()
        self.assertEqual(rc, 1)
        self.assertIn("CANDIDATE_INDEX_STALE", output)


if __name__ == "__main__":
    unittest.main()
