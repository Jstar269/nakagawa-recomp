"""Write the Windows resource script of one executable: its icon and its VERSIONINFO.

Task Manager, Explorer's Details tab and the firewall and notification prompts name a
program by the FileDescription in its VERSIONINFO resource and fall back to the file
name (``nakagawa_player.exe``, ``hst-ucus98701-v1.exe``) when there is none. The player
and every per-title executable get their own script from this tool, which the Makefile
compiles with windres:

* the player is "Nakagawa Recomp";
* a title is "<display name> (Nakagawa Recomp)", the display name read from the title
  manifest (or given with ``--title-name`` when a build has no manifest).

The version is NK_PLAYER_VERSION from src/player/ui/player_ui_nk.h, the number the
About page shows. The script holds no date, host name or absolute path, so two builds
of one commit produce the same bytes. The icon stays assets/brand/nakagawa.rc, which
the generated script includes (windres needs ``--include-dir assets/brand``).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
VERSION_HEADER = ROOT / "src" / "player" / "ui" / "player_ui_nk.h"

PRODUCT_NAME = "Nakagawa Recomp"
COMPANY_NAME = "the Nakagawa Recomp authors"
LEGAL_COPYRIGHT = "Copyright (C) 2026 the Nakagawa Recomp authors"

# Language 0x0409 (US English), code page 1200 (Unicode): the "040904B0" block name.
_LANG_BLOCK = "040904B0"
_VERSION_RE = re.compile(r'^#define\s+NK_PLAYER_VERSION\s+"([^"]+)"', re.M)
_NUMERIC_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)")
_VS_FF_PRERELEASE = 0x2


class ResourceError(ValueError):
    """The inputs cannot make a truthful VERSIONINFO."""


def read_version(header: Path = VERSION_HEADER) -> str:
    match = _VERSION_RE.search(header.read_text(encoding="utf-8"))
    if match is None:
        raise ResourceError(f"{header} defines no NK_PLAYER_VERSION")
    return match.group(1)


def numeric_version(version: str) -> tuple[int, int, int, int]:
    """``0.0.2-dev`` -> (0, 0, 2, 0): the four 16-bit fields of FILEVERSION."""
    match = _NUMERIC_RE.match(version)
    if match is None:
        raise ResourceError(f"version {version!r} does not start with MAJOR.MINOR.PATCH")
    fields = tuple(int(part) for part in match.groups()) + (0,)
    if any(field > 0xFFFF for field in fields):
        raise ResourceError(f"version {version!r} has a field above 65535")
    return fields  # type: ignore[return-value]


def title_name_from_manifest(path: Path) -> str:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ResourceError(f"cannot read title manifest {path}: {exc}") from exc
    name = data.get("display_name") if isinstance(data, dict) else None
    if not isinstance(name, str) or not name.strip():
        raise ResourceError(f"title manifest {path} has no display_name")
    return name.strip()


def _rc_string(text: str) -> str:
    """A resource-script string literal; the characters rc treats specially are escaped."""
    if not text or any(ord(ch) < 0x20 or ord(ch) > 0x7E for ch in text):
        raise ResourceError(f"{text!r} must be non-empty printable ASCII")
    return '"' + text.replace("\\", "\\\\").replace('"', '""') + '"'


def render(description: str, original_filename: str, version: str) -> str:
    """The complete resource script, as text with LF line endings."""
    fields = numeric_version(version)
    numeric = ",".join(str(field) for field in fields)
    flags = _VS_FF_PRERELEASE if "-" in version else 0
    strings = (
        ("CompanyName", COMPANY_NAME),
        ("FileDescription", description),
        ("FileVersion", version),
        ("InternalName", Path(original_filename).stem),
        ("LegalCopyright", LEGAL_COPYRIGHT),
        ("OriginalFilename", original_filename),
        ("ProductName", PRODUCT_NAME),
        ("ProductVersion", version),
    )
    lines = [
        "/* SPDX-License-Identifier: GPL-3.0-or-later */",
        "/* Copyright (C) 2026 the Nakagawa Recomp authors */",
        "/* Generated by tools/win_version_resource.py; do not edit. */",
        "",
        "/* The app icon (1 ICON), found through windres --include-dir assets/brand. */",
        '#include "nakagawa.rc"',
        "",
        "/* VS_VERSION_INFO is resource 1; 0x40004 is VOS_NT_WINDOWS32, type 1 VFT_APP. */",
        "1 VERSIONINFO",
        f" FILEVERSION {numeric}",
        f" PRODUCTVERSION {numeric}",
        " FILEFLAGSMASK 0x3fL",
        f" FILEFLAGS 0x{flags:x}L",
        " FILEOS 0x40004L",
        " FILETYPE 0x1L",
        " FILESUBTYPE 0x0L",
        "BEGIN",
        '    BLOCK "StringFileInfo"',
        "    BEGIN",
        f'        BLOCK "{_LANG_BLOCK}"',
        "        BEGIN",
    ]
    lines += [f"            VALUE {_rc_string(key)}, {_rc_string(value)}" for key, value in strings]
    lines += [
        "        END",
        "    END",
        '    BLOCK "VarFileInfo"',
        "    BEGIN",
        '        VALUE "Translation", 0x409, 1200',
        "    END",
        "END",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--output", required=True, type=Path, help="the .rc file to write")
    parser.add_argument("--original-filename", required=True,
                        help="the executable's file name, e.g. nakagawa_player.exe")
    which = parser.add_mutually_exclusive_group(required=True)
    which.add_argument("--player", action="store_true", help="describe the player")
    which.add_argument("--manifest", type=Path, help="describe the title of this manifest")
    which.add_argument("--title-name", help="describe a title that has no manifest")
    parser.add_argument("--version-header", type=Path, default=VERSION_HEADER,
                        help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        if args.player:
            description = PRODUCT_NAME
        else:
            name = (title_name_from_manifest(args.manifest) if args.manifest
                    else args.title_name.strip())
            description = f"{name} ({PRODUCT_NAME})"
        text = render(description, args.original_filename, read_version(args.version_header))
    except ResourceError as exc:
        print(f"win_version_resource: {exc}", file=sys.stderr)
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # Rewrite only on a change so a rebuild with unchanged inputs keeps the timestamp.
    if not args.output.is_file() or args.output.read_bytes() != text.encode("ascii"):
        args.output.write_bytes(text.encode("ascii"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
