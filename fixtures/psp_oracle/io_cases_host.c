/* ---- fake sceLibFont (mode fontlist) ------------------------------------------------------
 * Serves scenario-defined 168-byte style records, allocates through the case's own callbacks
 * (so the arena accounting is exercised), frees every block in DoneLib, and logs each call. */
#define FAKE_FONTS 80
#define FAKE_LIB_BLOCKS 64
static uint32_t s_fontlib_handle = 0x1234u;
static int s_fontlib_error_set = 1;
static uint32_t s_fontlib_error;
static int s_fontlib_allocs = 1;
static uint32_t s_fontlib_alloc_bytes = 4096u;
static int s_fontcount;
static int s_fontcount_error_set = 1;
static uint32_t s_fontcount_error;
static int s_fontlist_rc_set;
static int s_fontlist_rc;
static int s_fontdone_rc;
static uint8_t s_fake_styles[FAKE_FONTS][FONTLIST_STYLE_BYTES];
static int s_fontinfo_rc[FAKE_FONTS];
static FontListNewLibParams *s_fontlib_params;
static void *s_fontlib_blocks[FAKE_LIB_BLOCKS];
static int s_fontlib_block_count;

static int hex_bytes(const char *hex, uint8_t *out, size_t count) {
    for (size_t i = 0; i < count; i++) {
        unsigned int byte = 0;
        if (sscanf(hex + 2u * i, "%2x", &byte) != 1) return 0;
        out[i] = (uint8_t)byte;
    }
    return 1;
}

uint32_t sceFontNewLib(FontListNewLibParams *params, uint32_t *errorCode) {
    printf("CALL sceFontNewLib numFonts=%u alloc=%d free=%d open=%d close=%d read=%d seek=%d\n",
           (unsigned int)params->numFonts, params->allocFuncAddr != NULL,
           params->freeFuncAddr != NULL, params->openFuncAddr != NULL,
           params->closeFuncAddr != NULL, params->readFuncAddr != NULL,
           params->seekFuncAddr != NULL);
    s_fontlib_params = params;
    s_fontlib_block_count = 0;
    for (int i = 0; i < s_fontlib_allocs && i < FAKE_LIB_BLOCKS; i++) {
        void *block = params->allocFuncAddr
            ? params->allocFuncAddr(params->userDataAddr, s_fontlib_alloc_bytes) : NULL;
        printf("ALLOC bytes=%u ok=%d\n", (unsigned int)s_fontlib_alloc_bytes, block != NULL);
        if (block == NULL) {
            if (errorCode) *errorCode = 0x80460002u;
            return 0u;
        }
        memset(block, 0x11, s_fontlib_alloc_bytes);
        s_fontlib_blocks[s_fontlib_block_count++] = block;
    }
    if (s_fontlib_error_set && errorCode) *errorCode = s_fontlib_error;
    return s_fontlib_handle;
}

int sceFontDoneLib(uint32_t libHandle) {
    printf("CALL sceFontDoneLib handle=0x%08x\n", (unsigned int)libHandle);
    if (s_fontlib_params && s_fontlib_params->freeFuncAddr) {
        for (int i = 0; i < s_fontlib_block_count; i++) {
            s_fontlib_params->freeFuncAddr(s_fontlib_params->userDataAddr, s_fontlib_blocks[i]);
        }
    }
    s_fontlib_block_count = 0;
    return s_fontdone_rc;
}

int sceFontGetNumFontList(uint32_t libHandle, uint32_t *errorCode) {
    printf("CALL sceFontGetNumFontList handle=0x%08x\n", (unsigned int)libHandle);
    if (s_fontcount_error_set && errorCode) *errorCode = s_fontcount_error;
    return s_fontcount;
}

int sceFontGetFontList(uint32_t libHandle, void *fontStyles, int numFonts) {
    printf("CALL sceFontGetFontList handle=0x%08x numFonts=%d\n", (unsigned int)libHandle,
           numFonts);
    if (s_fontlist_rc_set) return s_fontlist_rc;
    int copied = 0;
    for (int i = 0; i < numFonts && i < FAKE_FONTS; i++) {
        memcpy((uint8_t *)fontStyles + (size_t)i * FONTLIST_STYLE_BYTES, s_fake_styles[i],
               FONTLIST_STYLE_BYTES);
        copied++;
    }
    return copied;
}

int sceFontGetFontInfoByIndexNumber(uint32_t libHandle, void *fontStyle, int fontIndex) {
    printf("CALL sceFontGetFontInfoByIndexNumber handle=0x%08x index=%d\n",
           (unsigned int)libHandle, fontIndex);
    if (fontIndex < 0 || fontIndex >= FAKE_FONTS) return (int)0x80460006;
    if (s_fontinfo_rc[fontIndex] != 0) return s_fontinfo_rc[fontIndex];
    memcpy(fontStyle, s_fake_styles[fontIndex], FONTLIST_STYLE_BYTES);
    return 0;
}

static uint8_t fake_byte(const FakeEntry *e, uint32_t i, int generation) {
    uint8_t value = (uint8_t)(((i * 31u) + e->seed) ^ (i >> 7));
    if (generation > 0 && e->unstable && i == 0u) value ^= 0x5au;
    return value;
}

static FakeEntry *fake_entry_named(const char *name) {
    for (int i = 0; i < s_entry_count; i++) {
        if (strcmp(s_entries[i].name, name) == 0) return &s_entries[i];
    }
    return NULL;
}

static int fake_fd_new(int kind, int entry, int generation) {
    for (int i = 0; i < FAKE_FDS; i++) {
        if (s_fds[i].kind == FD_FREE) {
            s_fds[i].kind = kind;
            s_fds[i].entry = entry;
            s_fds[i].position = 0u;
            s_fds[i].generation = generation;
            return 0x100 + i;
        }
    }
    return (int)0x80020320;
}

static FakeFd *fake_fd(SceUID fd) {
    if (fd < 0x100 || fd >= 0x100 + FAKE_FDS) return NULL;
    FakeFd *f = &s_fds[fd - 0x100];
    return f->kind == FD_FREE ? NULL : f;
}

static uint8_t fake_umd_byte(uint32_t offset) {
    static const uint8_t iso_descriptor[8] = {0x01u, 0x43u, 0x44u, 0x30u,
                                               0x30u, 0x31u, 0x01u, 0x00u};
    if (offset >= FAKE_UMD_SECTOR16_OFFSET &&
        offset < FAKE_UMD_SECTOR16_OFFSET + sizeof(iso_descriptor)) {
        return iso_descriptor[offset - FAKE_UMD_SECTOR16_OFFSET];
    }
    return (uint8_t)(((offset * 31u) + 7u) ^ (offset >> 7));
}

static SceOff fake_umd_seek(SceUID fd, SceOff offset, int whence) {
    FakeFd *f = fake_fd(fd);
    if (f == NULL || f->kind != FD_UMD_RAW) return (SceOff)-1;
    SceOff base;
    if (whence == SEEK_SET) {
        base = 0;
    } else if (whence == SEEK_CUR) {
        base = (SceOff)f->position;
    } else if (whence == SEEK_END) {
        base = (SceOff)FAKE_UMD_SIZE;
    } else {
        return (SceOff)-1;
    }
    if ((offset > 0 && base > INT64_MAX - offset) ||
        (offset < 0 && base < INT64_MIN - offset)) {
        return (SceOff)-1;
    }
    const SceOff position = base + offset;
    if (position < 0 || (uint64_t)position > UINT32_MAX) return (SceOff)-1;
    f->position = (uint32_t)position;
    return position;
}

static int fake_umd_read(SceUID fd, void *data, SceSize size) {
    FakeFd *f = fake_fd(fd);
    if (f == NULL || f->kind != FD_UMD_RAW || size > UMDRAW_BUFFER_BYTES) {
        return FAKE_BAD_FD;
    }
    const uint32_t left = f->position < FAKE_UMD_SIZE ? FAKE_UMD_SIZE - f->position : 0u;
    const uint32_t take = size < left ? size : left;
    for (uint32_t i = 0u; i < take; i++) {
        ((uint8_t *)data)[i] = fake_umd_byte(f->position + i);
    }
    f->position += take;
    return (int)take;
}

static const FakeDevice *fake_device(const char *path, int dir) {
    for (int i = 0; i < s_device_count; i++) {
        if (s_devices[i].dir == dir && strcmp(s_devices[i].path, path) == 0) return &s_devices[i];
    }
    return NULL;
}

static int fake_font_name(const char *path, const char *prefix) {
    size_t length = strlen(prefix);
    if (strncmp(path, prefix, length) != 0) return -1;
    for (int i = 0; i < s_entry_count; i++) {
        if (strcmp(s_entries[i].name, path + length) == 0) return i;
    }
    return -1;
}

SceUID sceIoDopen(const char *dirname) {
    int rc;
    const FakeDevice *device = fake_device(dirname, 1);
    if (strcmp(dirname, "flash0:/font") == 0) {
        rc = s_fontdir_rc >= 0 ? fake_fd_new(FD_LISTING, -1, 0) : s_fontdir_rc;
        s_listing_cursor = 0;
    } else if (strcmp(dirname, "flash0:/font/") == 0 && s_fontdir_slash_set) {
        rc = s_fontdir_slash_rc >= 0 ? fake_fd_new(FD_LISTING, -1, 0) : s_fontdir_slash_rc;
        s_listing_cursor = 0;
    } else if (device != NULL) {
        rc = device->rc >= 0 ? fake_fd_new(FD_DEVDIR, -1, 0) : device->rc;
    } else {
        rc = FAKE_NOT_FOUND;
    }
    printf("CALL sceIoDopen path=%s rc=0x%08x\n", dirname, (unsigned int)rc);
    return rc;
}

int sceIoDread(SceUID fd, SceIoDirent *dir) {
    FakeFd *f = fake_fd(fd);
    int rc;
    if (f == NULL || f->kind != FD_LISTING) {
        rc = FAKE_BAD_FD;
    } else if (s_dread_fail_at >= 0 && s_dread_count == s_dread_fail_at) {
        rc = s_dread_fail_rc;
    } else if (s_listing_cursor >= s_entry_count) {
        rc = 0;
    } else {
        const FakeEntry *e = &s_entries[s_listing_cursor++];
        if (dir->d_private != NULL) {
            printf("DREAD-PRIVATE-NOT-NULL\n");
        }
        memset(dir, 0, sizeof(*dir));
        dir->d_stat.st_mode = e->mode;
        dir->d_stat.st_attr = e->attr;
        dir->d_stat.st_size = e->listed;
        memcpy(dir->d_name, e->name, sizeof(dir->d_name));
        rc = 1;
    }
    s_dread_count++;
    printf("CALL sceIoDread fd=0x%x rc=0x%08x\n", (unsigned int)fd, (unsigned int)rc);
    return rc;
}

int sceIoDclose(SceUID fd) {
    FakeFd *f = fake_fd(fd);
    int rc = FAKE_BAD_FD;
    if (f != NULL && (f->kind == FD_LISTING || f->kind == FD_DEVDIR)) {
        f->kind = FD_FREE;
        rc = 0;
    }
    printf("CALL sceIoDclose fd=0x%x rc=0x%08x\n", (unsigned int)fd, (unsigned int)rc);
    return rc;
}

SceUID sceIoOpen(const char *file, int flags, SceMode mode) {
    int rc = FAKE_NOT_FOUND;
    int entry;
    const FakeDevice *device = fake_device(file, 0);
    if ((entry = fake_font_name(file, "flash0:/font/")) >= 0) {
        FakeEntry *e = &s_entries[entry];
        if (flags == PSP_O_RDONLY && FIO_S_ISREG(e->mode)) {
            rc = fake_fd_new(FD_FLASH0, entry, e->opens);
            e->opens++;
        } else if (flags != PSP_O_RDONLY) {
            rc = (int)0x8001000d;
        }
    } else if ((entry = fake_font_name(file, "host0:/fonts/")) >= 0) {
        FakeEntry *e = &s_entries[entry];
        if (!s_host_dir) {
            rc = FAKE_NOT_FOUND;
        } else if (flags == (PSP_O_WRONLY | PSP_O_CREAT | PSP_O_TRUNC)) {
            if (e->host_open_fails) {
                rc = e->host_open_rc;
            } else {
                free(e->host);
                e->host = NULL;
                e->host_bytes = 0u;
                e->host_written = 1;
                rc = fake_fd_new(FD_HOST_WRITE, entry, 0);
            }
        } else if (flags == PSP_O_RDONLY && e->host_written) {
            rc = fake_fd_new(FD_HOST_READ, entry, 0);
        }
    } else if (s_umdraw_mode && strcmp(file, "umd0:") == 0 &&
               (flags == PSP_O_RDONLY || flags == UMDIO_RAW_FLAGS)) {
        rc = device == NULL ? FAKE_NOT_FOUND
            : device->rc >= 0 ? fake_fd_new(FD_UMD_RAW, -1, 0) : device->rc;
    } else if (device != NULL) {
        rc = device->rc >= 0 ? fake_fd_new(FD_DEVICE, -1, 0) : device->rc;
    }
    printf("CALL sceIoOpen path=%s flags=0x%08x mode=0%o rc=0x%08x\n", file, (unsigned int)flags,
           (unsigned int)mode, (unsigned int)rc);
    return rc;
}

int sceIoRead(SceUID fd, void *data, SceSize size) {
    FakeFd *f = fake_fd(fd);
    int rc = FAKE_BAD_FD;
    if (f != NULL && f->kind == FD_FLASH0) {
        FakeEntry *e = &s_entries[f->entry];
        uint32_t left = e->bytes - f->position;
        uint32_t take = size < left ? size : left;
        if (e->read_fails && f->position + take > e->fail_after) {
            rc = e->fail_rc;
        } else {
            for (uint32_t i = 0; i < take; i++) {
                ((uint8_t *)data)[i] = fake_byte(e, f->position + i, f->generation);
            }
            f->position += take;
            rc = (int)take;
        }
    } else if (f != NULL && f->kind == FD_HOST_READ) {
        FakeEntry *e = &s_entries[f->entry];
        uint32_t left = e->host_bytes - f->position;
        uint32_t take = size < left ? size : left;
        memcpy(data, e->host + f->position, take);
        f->position += take;
        rc = (int)take;
    } else if (f != NULL && f->kind == FD_UMD_RAW) {
        rc = fake_umd_read(fd, data, size);
    }
    printf("CALL sceIoRead fd=0x%x size=%u rc=0x%08x\n", (unsigned int)fd, size, (unsigned int)rc);
    return rc;
}

SceOff sceIoLseek(SceUID fd, SceOff offset, int whence) {
    const SceOff rc = fake_umd_seek(fd, offset, whence);
    const uint64_t bits = (uint64_t)rc;
    printf("CALL sceIoLseek fd=0x%x offset=%lld whence=%d rc=0x%08x%08x\n",
           (unsigned int)fd, (long long)offset, whence,
           (unsigned int)(uint32_t)(bits >> 32), (unsigned int)(uint32_t)bits);
    return rc;
}

int sceIoLseek32(SceUID fd, int offset, int whence) {
    const SceOff result = fake_umd_seek(fd, (SceOff)offset, whence);
    const int rc = result < 0 ? (int)result : (int)result;
    printf("CALL sceIoLseek32 fd=0x%x offset=%d whence=%d rc=0x%08x\n",
           (unsigned int)fd, offset, whence, (unsigned int)rc);
    return rc;
}

int sceIoReadAsync(SceUID fd, void *data, SceSize size) {
    const int read_result = fake_umd_read(fd, data, size);
    int rc = FAKE_BAD_FD;
    if (read_result >= 0) {
        s_umdraw_async_fd = fd;
        s_umdraw_async_result = (SceOff)read_result;
        s_umdraw_async_pending = 1;
        rc = 0;
    }
    printf("CALL sceIoReadAsync fd=0x%x size=%u rc=0x%08x\n",
           (unsigned int)fd, size, (unsigned int)rc);
    return rc;
}

int sceIoPollAsync(SceUID fd, SceOff *result) {
    int rc = FAKE_BAD_FD;
    if (s_umdraw_async_pending && fd == s_umdraw_async_fd) {
        *result = s_umdraw_async_result;
        rc = 0;
    } else if (result != NULL) {
        *result = (SceOff)-1;
    }
    const uint64_t bits = (uint64_t)(result != NULL ? *result : 0);
    printf("CALL sceIoPollAsync fd=0x%x rc=0x%08x result=0x%08x%08x\n",
           (unsigned int)fd, (unsigned int)rc,
           (unsigned int)(uint32_t)(bits >> 32), (unsigned int)(uint32_t)bits);
    return rc;
}

int sceIoWaitAsync(SceUID fd, SceOff *result) {
    int rc = FAKE_BAD_FD;
    if (s_umdraw_async_pending && fd == s_umdraw_async_fd) {
        *result = s_umdraw_async_result;
        s_umdraw_async_pending = 0;
        s_umdraw_async_fd = -1;
        rc = 0;
    } else if (result != NULL) {
        *result = (SceOff)-1;
    }
    const uint64_t bits = (uint64_t)(result != NULL ? *result : 0);
    printf("CALL sceIoWaitAsync fd=0x%x rc=0x%08x result=0x%08x%08x\n",
           (unsigned int)fd, (unsigned int)rc,
           (unsigned int)(uint32_t)(bits >> 32), (unsigned int)(uint32_t)bits);
    return rc;
}

int sceIoGetstat(const char *file, SceIoStat *stat) {
    int rc = FAKE_NOT_FOUND;
    if (s_umdraw_mode && strcmp(file, "umd0:") == 0) {
        stat->st_mode = 0x21ff;
        stat->st_attr = 0u;
        stat->st_size = (SceOff)FAKE_UMD_SIZE;
        rc = 0;
    }
    printf("CALL sceIoGetstat path=%s rc=0x%08x\n", file, (unsigned int)rc);
    return rc;
}

int sceIoWrite(SceUID fd, const void *data, SceSize size) {
    FakeFd *f = fake_fd(fd);
    int rc = FAKE_BAD_FD;
    const char *name = "-";
    if (f != NULL && f->kind == FD_HOST_WRITE) {
        FakeEntry *e = &s_entries[f->entry];
        name = e->name;
        if (e->write_fails) {
            rc = e->write_rc;
        } else {
            uint32_t take = e->short_writes && size > 4096u ? 4096u : size;
            uint8_t *grown = (uint8_t *)realloc(e->host, (size_t)e->host_bytes + take + 1u);
            if (grown == NULL) {
                rc = (int)0x80020190;
            } else {
                e->host = grown;
                memcpy(e->host + e->host_bytes, data, take);
                if (e->host_corrupt && e->host_bytes == 0u && take > 0u) e->host[0] ^= 0xffu;
                e->host_bytes += take;
                rc = (int)take;
            }
        }
    }
    printf("CALL sceIoWrite fd=0x%x target=host0:/fonts/%s size=%u rc=0x%08x\n",
           (unsigned int)fd, name, size, (unsigned int)rc);
    return rc;
}

int sceIoClose(SceUID fd) {
    FakeFd *f = fake_fd(fd);
    int rc = FAKE_BAD_FD;
    if (f != NULL && (f->kind == FD_FLASH0 || f->kind == FD_HOST_WRITE ||
                      f->kind == FD_HOST_READ || f->kind == FD_DEVICE ||
                      f->kind == FD_UMD_RAW)) {
        f->kind = FD_FREE;
        rc = 0;
    }
    printf("CALL sceIoClose fd=0x%x rc=0x%08x\n", (unsigned int)fd, (unsigned int)rc);
    return rc;
}

int sceIoMkdir(const char *dir, SceMode mode) {
    int rc = (int)0x8001000d;
    if (strcmp(dir, "host0:/fonts") == 0) {
        rc = s_mkdir_rc;
        s_host_dir = 1;
    }
    printf("CALL sceIoMkdir path=%s mode=0%o rc=0x%08x\n", dir, (unsigned int)mode,
           (unsigned int)rc);
    return rc;
}

