static int hex_text(const char *hex, char *out, size_t capacity) {
    size_t length = strlen(hex);
    if (length % 2u != 0u || length / 2u >= capacity) return 0;
    for (size_t i = 0; i < length / 2u; i++) {
        unsigned int byte = 0;
        if (sscanf(hex + 2u * i, "%2x", &byte) != 1) return 0;
        out[i] = (char)byte;
    }
    out[length / 2u] = '\0';
    return 1;
}

/* A 32-bit scenario value: "0x80010002" is the PSP error code, negative as an int, on hosts
 * whose long is 32 bits as well as 64. */
static long number(const char *text) {
    return (long)(int32_t)(uint32_t)strtoull(text, NULL, 0);
}

static int load_scenario(FILE *input) {
    static char line[1024];
    while (fgets(line, sizeof(line), input) != NULL) {
        char w[8][160];
        line[strcspn(line, "\r\n")] = '\0';
        if (line[0] == '\0' || line[0] == '#') continue;
        if (strncmp(line, "fontentry ", 10) == 0) {
            /* The style bytes do not fit the %159s words below: parse this line on its own. */
            static char hex[512];
            unsigned int index = 0;
            if (sscanf(line, "fontentry %u %511s", &index, hex) != 2) return 0;
            if (index >= FAKE_FONTS || strlen(hex) != 2u * FONTLIST_STYLE_BYTES) return 0;
            if (!hex_bytes(hex, s_fake_styles[index], FONTLIST_STYLE_BYTES)) return 0;
            continue;
        }
        int n = sscanf(line, "%159s %159s %159s %159s %159s %159s %159s %159s",
                       w[0], w[1], w[2], w[3], w[4], w[5], w[6], w[7]);
        if (strcmp(w[0], "fontdir") == 0 && n == 3) {
            s_fontdir_rc = (int)number(w[1]);
            if (strcmp(w[2], "-") != 0) {
                s_fontdir_slash_rc = (int)number(w[2]);
                s_fontdir_slash_set = 1;
            }
        } else if (strcmp(w[0], "entry") == 0 && (n == 6 || n == 7)) {
            if (s_entry_count >= FAKE_ENTRIES) return 0;
            FakeEntry *e = &s_entries[s_entry_count++];
            memset(e, 0, sizeof(*e));
            e->mode = (int)number(w[1]);
            e->attr = (unsigned int)number(w[2]);
            if (strcmp(w[3], "-") != 0 && !hex_text(w[3], e->name, sizeof(e->name))) return 0;
            e->bytes = (uint32_t)number(w[4]);
            e->seed = (uint32_t)number(w[5]);
            e->listed = n == 7 ? (int64_t)strtoll(w[6], NULL, 0) : (int64_t)e->bytes;
        } else if (strcmp(w[0], "option") == 0 && n >= 3) {
            FakeEntry *e = fake_entry_named(w[2]);
            if (strcmp(w[1], "mkdir-rc") == 0) {
                s_mkdir_rc = (int)number(w[2]);
            } else if (strcmp(w[1], "dread-fails") == 0 && n == 4) {
                s_dread_fail_at = (int)number(w[2]);
                s_dread_fail_rc = (int)number(w[3]);
            } else if (e == NULL) {
                return 0;
            } else if (strcmp(w[1], "read-fails") == 0 && n == 5) {
                e->read_fails = 1;
                e->fail_after = (uint32_t)number(w[3]);
                e->fail_rc = (int)number(w[4]);
            } else if (strcmp(w[1], "unstable") == 0) {
                e->unstable = 1;
            } else if (strcmp(w[1], "host-open-fails") == 0 && n == 4) {
                e->host_open_fails = 1;
                e->host_open_rc = (int)number(w[3]);
            } else if (strcmp(w[1], "write-fails") == 0 && n == 4) {
                e->write_fails = 1;
                e->write_rc = (int)number(w[3]);
            } else if (strcmp(w[1], "short-writes") == 0) {
                e->short_writes = 1;
            } else if (strcmp(w[1], "host-corrupt") == 0) {
                e->host_corrupt = 1;
            } else {
                return 0;
            }
        } else if ((strcmp(w[0], "open") == 0 || strcmp(w[0], "dopen") == 0) && n == 3) {
            if (s_device_count >= FAKE_DEVICES) return 0;
            FakeDevice *d = &s_devices[s_device_count++];
            if (!hex_text(w[1], d->path, sizeof(d->path))) return 0;
            d->rc = (int)number(w[2]);
            d->dir = strcmp(w[0], "dopen") == 0;
        } else if (strcmp(w[0], "umd") == 0 && n == 3) {
            s_umd_medium = (int)number(w[1]);
            s_umd_drive = (int)number(w[2]);
        } else if (strcmp(w[0], "fontlib") == 0 && n == 5) {
            s_fontlib_handle = (uint32_t)number(w[1]);
            s_fontlib_error_set = strcmp(w[2], "-") != 0;
            if (s_fontlib_error_set) s_fontlib_error = (uint32_t)number(w[2]);
            s_fontlib_allocs = (int)number(w[3]);
            s_fontlib_alloc_bytes = (uint32_t)number(w[4]);
        } else if (strcmp(w[0], "fontcount") == 0 && n == 3) {
            s_fontcount = (int)number(w[1]);
            s_fontcount_error_set = strcmp(w[2], "-") != 0;
            if (s_fontcount_error_set) s_fontcount_error = (uint32_t)number(w[2]);
        } else if (strcmp(w[0], "fontlist-rc") == 0 && n == 2) {
            s_fontlist_rc_set = 1;
            s_fontlist_rc = (int)number(w[1]);
        } else if (strcmp(w[0], "fontinfo-rc") == 0 && n == 3) {
            long index = number(w[1]);
            if (index < 0 || index >= FAKE_FONTS) return 0;
            s_fontinfo_rc[index] = (int)number(w[2]);
        } else if (strcmp(w[0], "fontdone-rc") == 0 && n == 2) {
            s_fontdone_rc = (int)number(w[1]);
        } else {
            return 0;
        }
    }
    return 1;
}

int main(int argc, char **argv) {
    if (argc != 2 ||
        (strcmp(argv[1], "fonts") != 0 && strcmp(argv[1], "umd") != 0 &&
         strcmp(argv[1], "fontlist") != 0) ||
        !load_scenario(stdin)) {
        fprintf(stderr, "io_cases_host: usage: io_cases_host fonts|umd|fontlist < scenario\n");
        return 2;
    }
    if (strcmp(argv[1], "fonts") == 0) {
        static FontFiles fonts;
        memset(&fonts, 0, sizeof(fonts));
        fonts.emit = harness_emit;
        fonts.step = harness_step;
        fontfiles_run(&fonts);
    } else if (strcmp(argv[1], "umd") == 0) {
        static UmdIo umd;
        memset(&umd, 0, sizeof(umd));
        umd.emit = harness_emit;
        umd.step = harness_step;
        umdio_run(&umd);
    } else {
        static FontList fontlist;
        memset(&fontlist, 0, sizeof(fontlist));
        fontlist.emit = harness_emit;
        fontlist.step = harness_step;
        fontlist_run(&fontlist);
    }
    for (int i = 0; i < s_entry_count; i++) {
        const FakeEntry *e = &s_entries[i];
        if (!e->host_written) continue;
        int equal = e->host_bytes == e->bytes;
        for (uint32_t b = 0; equal && b < e->bytes; b++) {
            equal = e->host[b] == fake_byte(e, b, 0);
        }
        printf("HOST0 name=%s bytes=%u equal=%d\n", e->name, e->host_bytes, equal);
    }
    int open_fds = 0;
    for (int i = 0; i < FAKE_FDS; i++) {
        if (s_fds[i].kind != FD_FREE) open_fds++;
    }
    printf("SUMMARY open_fds=%d\n", open_fds);
    return 0;
}
