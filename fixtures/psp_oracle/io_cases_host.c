/* Host harness for font_files.h (case font-files), umd_io.h (cases umd-io and umd-raw-read) and
 * font_list.h (case font-list): runs the probe's code against a fake file system and a fake font
 * library and logs every call, so tools/test_psp_oracle.py can check safety rules without a PSP.
 *
 * usage: io_cases_host fonts|umd|umdraw|fontlist < scenario
 *
 * The raw UMD mode adds only read, seek, async and stat calls to read-only opens and closes.
 * Unknown calls fail compilation under -Werror. Available calls are sceIoDopen, sceIoDread,
 * sceIoDclose, sceIoOpen, sceIoRead, sceIoWrite, sceIoClose, sceIoLseek, sceIoLseek32,
 * sceIoReadAsync, sceIoPollAsync, sceIoWaitAsync, sceIoGetstat, sceIoMkdir,
 * sceUmdCheckMedium, and sceUmdGetDriveStat.
 *
 * Scenario lines:
 *   fontdir <rc> <rc_slash>          sceIoDopen("flash0:/font") / ("flash0:/font/") result;
 *                                    a non-negative value opens the listing (default 0 and -)
 *   entry <mode> <attr> <name-hex> <bytes> <seed> [<listed-size>]
 *                                    a listing entry; regular files hold <bytes> generated bytes
 *                                    byte[i] = (i * 31 + seed) ^ (i >> 7)
 *   option mkdir-rc <rc>             sceIoMkdir("host0:/fonts") result (default 0)
 *   option dread-fails <n> <rc>      the (n+1)th sceIoDread returns <rc>
 *   option read-fails <name> <after> <rc>   flash0 reads of <name> fail once <after> bytes are read
 *   option unstable <name>           a second flash0 open of <name> returns changed bytes
 *   option host-open-fails <name> <rc>      host0 write-open of <name> returns <rc>
 *   option write-fails <name> <rc>   host0 writes of <name> return <rc>
 *   option short-writes <name>       host0 writes of <name> accept at most 4096 bytes each
 *   option host-corrupt <name>       the stored host0 copy of <name> has its first byte flipped
 *   open <path-hex> <rc>             sceIoOpen of a device path returns <rc> (>= 0 opens)
 *   dopen <path-hex> <rc>            sceIoDopen of a device path returns <rc> (>= 0 opens)
 *   umd <medium> <drive-stat>        sceUmdCheckMedium / sceUmdGetDriveStat results
 *   umdraw uses a synthetic byte-addressed 128-sector UMD with a public ISO header at LBA 16
 *   fontlib <handle> <err|-> <allocs> <bytes>
 *                                    sceFontNewLib: the handle it returns, the error word it
 *                                    writes (- leaves it untouched), and how many blocks of
 *                                    <bytes> it allocates through the case's callback first;
 *                                    a refused allocation makes it fail (handle 0)
 *   fontcount <count> <err|->        sceFontGetNumFontList result and error word
 *   fontlist-rc <rc>                 sceFontGetFontList returns <rc> and copies nothing
 *   fontentry <index> <hex168>       the 168 style bytes served for <index> (list and info)
 *   fontinfo-rc <index> <rc>         sceFontGetFontInfoByIndexNumber(<index>) returns <rc>
 *   fontdone-rc <rc>                 sceFontDoneLib result
 * Unlisted device paths answer 0x80010002. Numbers accept 0x prefixes; names are literal.
 * Output: CALL, EMIT, STEP and HOST0 lines, then a SUMMARY line. */

